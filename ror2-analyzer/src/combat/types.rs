#[derive(Debug, Clone, PartialEq)]
pub struct Bleed {
    pub target: TargetId,
    pub duration_seconds: f64,
    pub ticks_per_second: f64,
    pub damage_per_tick: f64,
}

impl Bleed {
    pub fn nominal_ticks(&self) -> f64 {
        self.duration_seconds * self.ticks_per_second
    }

    pub fn nominal_total_damage(&self) -> f64 {
        self.nominal_ticks() * self.damage_per_tick
    }
}

#[derive(Debug, Clone, PartialEq)]
pub enum GeneratedEffect {
    Hit(GeneratedHit),
    Bleed(Bleed),
}

#[derive(Debug, Clone, PartialEq)]
pub struct ScheduledEvent {
    pub time: Duration,
    pub effect: GeneratedEffect,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct EventQueue {
    events: Vec<ScheduledEvent>,
}

impl EventQueue {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn len(&self) -> usize {
        self.events.len()
    }

    pub fn is_empty(&self) -> bool {
        self.events.is_empty()
    }

    pub fn schedule_at(&mut self, time: Duration, effect: GeneratedEffect) {
        self.events.push(ScheduledEvent { time, effect });
    }

    pub fn schedule_after(
        &mut self,
        current_time: Duration,
        delay: Duration,
        effect: GeneratedEffect,
    ) {
        let time = current_time
            .checked_add(delay)
            .expect("combat event time overflow");

        self.schedule_at(time, effect);
    }

    pub fn iter(&self) -> impl Iterator<Item = &ScheduledEvent> {
        self.events.iter()
    }

    /// Remove and return every event occurring at the
    /// earliest timestamp.
    ///
    /// Events in the returned Vec are simultaneous.
    pub fn pop_next_batch(&mut self) -> Option<(Duration, Vec<ScheduledEvent>)> {
        let next_time = self.events.iter().map(|event| event.time).min()?;

        let mut batch = Vec::new();
        let mut remaining = Vec::with_capacity(self.events.len());

        for event in self.events.drain(..) {
            if event.time == next_time {
                batch.push(event);
            } else {
                remaining.push(event);
            }
        }

        self.events = remaining;

        Some((next_time, batch))
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct ProcOutcome {
    pub probability: f64,
    pub effects: Vec<GeneratedEffect>,
}

impl ProcOutcome {
    pub fn hits(&self) -> impl Iterator<Item = &GeneratedHit> {
        self.effects.iter().filter_map(|effect| match effect {
            GeneratedEffect::Hit(hit) => Some(hit),
            _ => None,
        })
    }

    pub fn bleeds(&self) -> impl Iterator<Item = &Bleed> {
        self.effects.iter().filter_map(|effect| match effect {
            GeneratedEffect::Bleed(bleed) => Some(bleed),
            _ => None,
        })
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct ResolvedHit {
    pub source: ProcKind,
    pub hit: Hit,
    pub targeting: AttackTargeting,
    pub effects: Vec<ResolvedEffect>,
}

#[derive(Debug, Clone, PartialEq)]
pub enum ResolvedEffect {
    Hit(ResolvedHit),
    Bleed(Bleed),
}

impl ResolvedEffect {
    pub fn total_damage(&self) -> f64 {
        match self {
            ResolvedEffect::Hit(resolved_hit) => {
                resolved_hit.hit.final_damage
                    + resolved_hit
                        .effects
                        .iter()
                        .map(ResolvedEffect::total_damage)
                        .sum::<f64>()
            }

            ResolvedEffect::Bleed(bleed) => bleed.nominal_total_damage(),
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct CombatOutcome {
    pub probability: f64,
    pub effects: Vec<ResolvedEffect>,
}

impl CombatOutcome {
    pub fn total_generated_damage(&self) -> f64 {
        self.effects.iter().map(ResolvedEffect::total_damage).sum()
    }

    pub fn total_damage_with_root(&self, root: &Hit) -> f64 {
        root.final_damage + self.total_generated_damage()
    }
}
